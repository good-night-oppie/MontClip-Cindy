// Generates a literal Node-only checker in the workflow. No checkout, downloads, or npm install.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
export const FILES = ["rules.mjs", "run.mjs", "policy.json", "teammates.json"];
export function workflowText() {
  const payload = Object.fromEntries(FILES.map((name) => {
    const bytes = fs.readFileSync(path.join(here, name));
    return [name, { base64: bytes.toString("base64"), sha256: createHash("sha256").update(bytes).digest("hex") }];
  }));
  const code = [
    'import fs from "node:fs";', 'import os from "node:os";', 'import path from "node:path";',
    'import { createHash } from "node:crypto";', 'import { pathToFileURL } from "node:url";',
    `const payload = ${JSON.stringify(payload)};`,
    'const dir = fs.mkdtempSync(path.join(os.tmpdir(), "pr-sop-"));',
    'for (const [name, item] of Object.entries(payload)) {',
    '  const bytes = Buffer.from(item.base64, "base64");',
    '  if (createHash("sha256").update(bytes).digest("hex") !== item.sha256) throw Error("checker integrity mismatch");',
    '  fs.writeFileSync(path.join(dir, name), bytes);', '}',
    'try { const { main } = await import(pathToFileURL(path.join(dir, "run.mjs"))); process.exitCode = await main(); }',
    'catch { console.error("检查未完成：请核对只读API权限、网络及最新PR事件；不能当作通过。"); process.exitCode = 1; }'
  ];
  return `# Generated by node scripts/pr-sop/make-workflow.mjs; do not hand-edit embedded checker.
name: sop-pr-lint
on:
  # Trusted default/base workflow only. Never checkout or run PR code/dependencies.
  # No cache, artifacts, secrets, or PR text interpolated into shell commands.
  # Owner decision: target-only; QQ manually reruns the trusted check after exception review.
  pull_request_target:
    types: [opened, edited, synchronize, ready_for_review, reopened, review_requested, review_request_removed]
permissions:
  pull-requests: read
  contents: read
  issues: read
jobs:
  metadata:
    name: sop-pr-lint
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - name: Read PR metadata only (no checkout)
        env:
          GITHUB_TOKEN: \${{ github.token }}
        shell: bash
        run: |
          node --input-type=module <<'PR_SOP_NODE'
${code.map((line) => "          " + line).join("\n")}
          PR_SOP_NODE
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = path.resolve(here, "../../.github/workflows/pr-sop.yml");
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, workflowText());
}
